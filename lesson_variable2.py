'''
 用Python记录去超市买的东西和价格，并打印购物信息。
'''

item_1 = "牛奶"     #商品名
price_1 = 13.0      #商品价格
item_2 = "鸡蛋"     #商品名
price_2 = 22.0        #商品价格
item_3 = "面包"     #商品名
price_3 = 11.8      #商品价格

total = price_1 + price_2 +price_3

print(f"我买了{item_1}、{item_2}和{item_3},一共花了{total}")
# 输出：我买了牛奶、鸡蛋和面包,一共花了46.8。